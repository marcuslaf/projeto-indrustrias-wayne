create extension if not exists "pgcrypto" with schema "extensions";

create table if not exists "public"."profiles" (
    "id" uuid not null references "auth"."users" on delete cascade,
    "username" text not null,
    "role" text not null default 'funcionario'::text check (role in ('funcionario', 'gerente', 'admin_seguranca')),
    "nome" text not null,
    "email" text,
    "created_at" timestamptz not null default now(),
    "updated_at" timestamptz not null default now(),
    constraint "profiles_pkey" primary key ("id"),
    constraint "profiles_username_key" unique ("username")
);

create table if not exists "public"."resources" (
    "id" bigint generated by default as identity not null,
    "name" text not null,
    "type" text not null check (type in ('equipamento', 'veiculo', 'dispositivo_seguranca')),
    "serial_number" text,
    "plate" text,
    "location" text not null,
    "status" text not null default 'disponivel'::text check (status in ('disponivel', 'em_uso', 'em_manutencao')),
    "acquisition_date" date not null,
    "last_maintenance_date" date,
    "created_by" uuid references "public"."profiles"("id") on delete set null,
    "created_at" timestamptz not null default now(),
    "updated_at" timestamptz not null default now(),
    "deleted_at" timestamptz,
    constraint "resources_pkey" primary key ("id")
);

create table if not exists "public"."service_orders" (
    "id" bigint generated by default as identity not null,
    "title" text not null,
    "description" text,
    "resource_id" bigint references "public"."resources"("id") on delete set null,
    "assigned_to" uuid references "public"."profiles"("id") on delete set null,
    "priority" text not null default 'media'::text check (priority in ('baixa', 'media', 'alta', 'urgente')),
    "status" text not null default 'aberta'::text check (status in ('aberta', 'em_andamento', 'concluida', 'cancelada')),
    "created_by" uuid references "public"."profiles"("id") on delete set null,
    "created_at" timestamptz not null default now(),
    "updated_at" timestamptz not null default now(),
    constraint "service_orders_pkey" primary key ("id")
);

create table if not exists "public"."maintenance_history" (
    "id" bigint generated by default as identity not null,
    "resource_id" bigint not null references "public"."resources"("id") on delete cascade,
    "description" text not null,
    "performed_by" text,
    "maintenance_date" date not null default current_date,
    "cost" numeric(10,2),
    "created_at" timestamptz not null default now(),
    constraint "maintenance_history_pkey" primary key ("id")
);

create table if not exists "public"."access_logs" (
    "id" bigint generated by default as identity not null,
    "user_id" uuid references "auth"."users"("id") on delete set null,
    "access_area" text not null,
    "access_time" timestamptz not null default now(),
    "status" text not null default 'sucesso'::text check (status in ('sucesso', 'falha')),
    "ip_address" text,
    constraint "access_logs_pkey" primary key ("id")
);

create table if not exists "public"."audit_logs" (
    "id" bigint generated by default as identity not null,
    "org_id" text,
    "user_id" uuid references "auth"."users"("id") on delete set null,
    "action" text not null,
    "entity" text not null,
    "entity_id" text,
    "old_data" jsonb,
    "new_data" jsonb,
    "ip_address" text,
    "created_at" timestamptz not null default now(),
    constraint "audit_logs_pkey" primary key ("id")
);

