create or replace function "public"."handle_new_user"()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
    insert into "public"."profiles" (id, username, role, nome, email)
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'username', 'user_' || substr(new.id::text, 1, 8)),
        coalesce(new.raw_user_meta_data ->> 'role', 'funcionario'),
        coalesce(new.raw_user_meta_data ->> 'nome', 'Usuario'),
        new.email
    );
    return new;
end;
$$;

create or replace function "public"."admin_delete_user"(user_id uuid)
returns void
language plpgsql
security definer set search_path = ''
as $$
begin
    if not exists (select 1 from "public"."profiles" where id = auth.uid() and role = 'admin_seguranca') then
        raise exception 'Apenas admin_seguranca pode excluir usuarios';
    end if;
    delete from "auth"."users" where id = user_id;
end;
$$;

create or replace function "public"."delete_old_logs"(days integer)
returns void
language plpgsql
security definer set search_path = ''
as $$
begin
    if not exists (select 1 from "public"."profiles" where id = auth.uid() and role = 'admin_seguranca') then
        raise exception 'Apenas admin_seguranca pode limpar logs';
    end if;
    delete from "public"."access_logs" where access_time < now() - (days || ' days')::interval;
end;
$$;

drop trigger if exists "on_auth_user_created" on "auth"."users";
create trigger "on_auth_user_created"
    after insert on "auth"."users"
    for each row
    execute function "public"."handle_new_user"();
